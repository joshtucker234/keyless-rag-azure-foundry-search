"""Run every sample question through the app and write SAMPLE_QUESTIONS.md + samples_results.json."""
import json
import os
import re
import sys

import app
import samples

HERE = os.path.dirname(os.path.abspath(__file__))
mode = sys.argv[1] if len(sys.argv) > 1 else "hybrid + semantic"


def fmt_pages(pages: dict) -> str:
    parts = []
    for sub, pg in pages.items():
        shown = ", ".join(map(str, pg[:10])) + (", ..." if len(pg) > 10 else "")
        parts.append(f"{sub}: p.{shown}")
    return "; ".join(parts) if parts else "none (should refuse)"


results, lines = [], []
passed = 0
for s in samples.load():
    r = app.answer(s["question"], mode=mode)
    c = samples.check(s, r)
    passed += c["passed"]
    cited = sorted({int(n) for n in re.findall(r"\[(\d+)\]", r["text"])})
    results.append({"id": s["id"], "question": s["question"], "check": c, "answer": r["text"],
                    "sources": [app.cite(d) for d in r["docs"]]})
    print(f"{'PASS' if c['passed'] else 'FAIL'}  {s['id']} {s['category']:10} {s['question'][:60]}  {c}")
    lines += [
        f"### {s['id']} · {s['question']}",
        f"*Type: {s['category']}*  ·  **Result in this run: {'✅ pass' if c['passed'] else '❌ fail'}**",
        "",
        f"- **Expect:** {s['expect']}",
        f"- **Expected source:** {fmt_pages(s['expected_pages'])}",
        f"- **Got:** {r['text'].strip()}",
        "- **Retrieved sources:** " + (", ".join(("**" if i in cited else "") + app.cite(d) + ("**" if i in cited else "")
                                                   for i, d in enumerate(r["docs"], 1)) or "none") + "  *(bold = cited in the answer)*",
        "",
    ]

header = [
    "# Lab 1 sample questions: what to expect",
    "",
    f"Generated by `run_samples.py` using **{mode}** retrieval. **{passed} of {len(results)}** passed in this run.",
    "",
    "**How to read this**",
    "- *Expected source* pages come from searching the original PDFs for the answer's key phrases, not from the search index. "
    "Several terms appear on many pages, so any listed page counts as correct.",
    "- Pages are **PDF page indexes** (1 = first page of the file), not the numbers printed on the pages.",
    "- A question passes when the answer cites a source on an expected page of the expected document and contains the key points.",
    "- Types: *exact* = distinctive terms; *paraphrase* = different wording from the document; *neighbor* = a similar sibling "
    "document exists; *none* = not in the documents, the app should refuse.",
    "- Model wording varies run to run. Check the facts and the source, not the exact sentence.",
    "",
]
open(os.path.join(HERE, "SAMPLE_QUESTIONS.md"), "w", encoding="utf-8").write("\n".join(header + lines))
json.dump(results, open(os.path.join(HERE, "samples_results.json"), "w"), indent=1)
print(f"\n{passed}/{len(results)} passed ({mode}). Wrote SAMPLE_QUESTIONS.md")
